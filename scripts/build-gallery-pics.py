"""Build the gallery page's responsive stills from a folder of originals.

python scripts/build-gallery-pics.py "C:/path/to/gallery"

Reads JPEG, PNG, WebP and HEIC (needs `pip install pillow-heif`), in name
order. Each picture becomes pNN at 320/640/960/1600/2400 px wide (never
upscaled), WebP quality 84, in pics/gallery/responsive/. Writes
js/gallery-data.js and prints the id list for PHOTOS in js/gallery-wall.js.
The originals are only read, never changed.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageOps

try:
    import pillow_heif
    pillow_heif.register_heif_opener()
except ImportError:
    pillow_heif = None

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'pics/gallery/responsive'
TYPES = ('.jpg', '.jpeg', '.png', '.webp', '.heic', '.heif')


def main():
    source_dir = Path(sys.argv[1])
    files = sorted(p for p in source_dir.iterdir() if p.suffix.lower() in TYPES)
    if any(p.suffix.lower() in ('.heic', '.heif') for p in files) and not pillow_heif:
        sys.exit('HEIC files found: run  pip install pillow-heif  first.')
    OUT.mkdir(parents=True, exist_ok=True)
    pictures = {}
    for index, source in enumerate(files, 1):
        stem = f'p{index:02d}'
        with Image.open(source) as image:
            image = ImageOps.exif_transpose(image).convert('RGB')
            sources = []
            for width in sorted({min(w, image.width) for w in (320, 640, 960, 1600, 2400)}):
                name = f'pics/gallery/responsive/{stem}-{width}.webp'
                resized = image.copy()
                resized.thumbnail((width, 100000), Image.Resampling.LANCZOS)
                resized.save(ROOT / name, 'WEBP', quality=84, method=6)
                sources.append({'src': name, 'width': width})
            pictures[stem] = {'width': image.width, 'height': image.height, 'sources': sources}
        print(f'{stem}  {image.width}x{image.height}  <- {source.name}')
    (ROOT / 'js/gallery-data.js').write_text(
        '// Generated by scripts/build-gallery-pics.py; no media is fetched here.\n'
        'window.galleryPictures = ' + json.dumps(pictures, separators=(',', ':')) + ';\n',
        encoding='utf-8')
    print('PHOTOS =', json.dumps(list(pictures)))


if __name__ == '__main__':
    main()
